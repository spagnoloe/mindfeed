// Regenerates src/design/icons.generated.ts from Google's Material Symbols Rounded SVGs, at the
// axes the design uses (opsz 24, wght 500, GRAD 0) in outlined (FILL 0) and filled (FILL 1).
// To add an icon, add its name to ICONS and run `pnpm --filter mobile icons`.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ICONS = [
  'add',
  'arrow_back',
  'arrow_forward',
  'check_circle',
  'chevron_right',
  'collections_bookmark',
  'delete',
  'edit',
  'explore',
  'favorite',
  'home',
  'interests',
  'keyboard_arrow_down',
  'keyboard_arrow_up',
  'library_add',
  'lightbulb',
  'menu_book',
  'person',
  'radio_button_unchecked',
  'remove_circle',
  'search',
  'stacks',
  'tag',
  'trending_up',
];

// Names the design uses that are ligature aliases of another icon's SVG (same codepoint in the font).
const SVG_NAME = { remove_circle: 'do_not_disturb_on' };

const BASE = 'https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web';
const OUT = fileURLToPath(new URL('../src/design/icons.generated.ts', import.meta.url));

async function pathData(name, variant) {
  const file = SVG_NAME[name] ?? name;
  const url = `${BASE}/${file}/materialsymbolsrounded/${file}_${variant}_24px.svg`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} fetching ${url}`);
  const svg = await response.text();
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`Unexpected viewBox in ${url}`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`No paths in ${url}`);
  return paths.join(' ');
}

const entries = await Promise.all(
  ICONS.map(async (name) => [name, await pathData(name, 'wght500'), await pathData(name, 'wght500fill1')]),
);

const body = entries
  .map(([name, outlined, filled]) => `  ${name}: {\n    outlined: '${outlined}',\n    filled: '${filled}',\n  },`)
  .join('\n');

await writeFile(
  OUT,
  `// Generated by scripts/generate-icons.mjs. Do not edit.
// Material Symbols Rounded (Apache License 2.0), opsz 24, wght 500, GRAD 0, viewBox 0 -960 960 960.
export const iconPaths = {
${body}
} as const;
`,
);
console.log(`Wrote ${entries.length} icons to ${OUT}`);
